export function localizeSceneOrNote(text: string, locale: StudioLocale): string {
  if (!text) return text;
  for (const [tr, en] of STARTER_TEXT_PAIRS) {
    if (text === tr || text === en) return locale === 'en' ? en : tr;
  }
  if (locale === 'en') {
    const mSc = text.match(/^Sahne (\d+)$/);
    if (mSc) return `Scene ${mSc[1]}`;
    const mKp = text.match(/^Canlı Kukla #(\d+)$/);
    if (mKp) return `Live Puppet #${mKp[1]}`;
  } else {
    const mSc = text.match(/^Scene (\d+)$/);
    if (mSc) return `Sahne ${mSc[1]}`;
    const mKp = text.match(/^Live Puppet #(\d+)$/);
    if (mKp) return `Canlı Kukla #${mKp[1]}`;
  }
  return text;
}

