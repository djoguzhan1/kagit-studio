export const TRANSLATIONS: Record<StudioLocale, Record<TranslationKey, string>> = {
  tr: TR,
  en: EN,
};

export function translate(locale: StudioLocale, key: TranslationKey): string {
  return TRANSLATIONS[locale]?.[key] ?? TR[key];
}

export function useT(): (key: TranslationKey) => string {
  const locale = useStudioStore((s) => s.locale);
  return (key: TranslationKey) => translate(locale, key);
}

export function translateFmt(
  locale: StudioLocale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  let out = translate(locale, key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.split(`{${k}}`).join(String(v));
    }
  }
  return out;
}

export function useTFmt(): (key: TranslationKey, vars?: Record<string, string | number>) => string {
  const locale = useStudioStore((s) => s.locale);
  return (key: TranslationKey, vars?: Record<string, string | number>) =>
    translateFmt(locale, key, vars);
}

/** Keeps <html lang>, <title>, and <meta name="description"> 100% synced in both TR and EN */
export function applyDocumentLocale(locale: StudioLocale): void {
  if (typeof document === 'undefined') return;
  document.documentElement.setAttribute('lang', locale);
  document.title = translate(locale, 'docPageTitle');
  const descMeta = document.querySelector('meta[name="description"]');
  if (descMeta) {
    descMeta.setAttribute('content', translate(locale, 'docMetaDescription'));
  }
}

